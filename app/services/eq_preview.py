"""Render a track's volume and EQ from cached PCM for Qt Multimedia playback."""

from concurrent.futures import CancelledError
from math import cos, log, pi, sin, sinh, sqrt
from pathlib import Path
from threading import Event

import numpy as np

from app.services.audio_decode import AudioDecodeError, pcm_info, read_pcm

PEAK_LIMIT = 0.95
_PCM_CACHE_BYTES = 64 * 1024 * 1024
_BLOCK_FRAMES = 65_536


def _biquad(name: str, frequency: float, gain: float, rate: int) -> np.ndarray:
    # RBJ audio EQ cookbook, with the same octave width and shelf Q as export.
    omega = 2 * pi * frequency / rate
    c, s = cos(omega), sin(omega)
    amplitude = 10 ** (gain / 40)
    if name == "equalizer":
        alpha = s * sinh(log(2) * omega / s)  # Two octaves.
        coefficients = (1 + alpha * amplitude, -2 * c, 1 - alpha * amplitude,
                        1 + alpha / amplitude, -2 * c, 1 - alpha / amplitude)
    else:
        total, difference = amplitude + 1, amplitude - 1
        beta = 2 * sqrt(amplitude) * s  # Shelf Q = 0.5.
        if name == "lowshelf":
            coefficients = (
                amplitude * (total - difference * c + beta),
                2 * amplitude * (difference - total * c),
                amplitude * (total - difference * c - beta),
                total + difference * c + beta, -2 * (difference + total * c),
                total + difference * c - beta,
            )
        else:
            coefficients = (
                amplitude * (total + difference * c + beta),
                -2 * amplitude * (difference + total * c),
                amplitude * (total + difference * c - beta),
                total - difference * c + beta, 2 * (difference - total * c),
                total - difference * c - beta,
            )
    return np.asarray(coefficients) / coefficients[3]


def _apply_eq(pcm: np.ndarray, rate: int, audio_filter: str, cancel: Event) -> np.ndarray:
    from scipy.signal import sosfilt

    sections = []
    volume = 1.0
    for item in audio_filter.split(","):
        # These are the filters generated by PlaylistTrack.audio_filter.
        name, spec = item.split("=", 1)
        if name == "volume":
            volume = 10 ** (float(spec.removesuffix("dB")) / 20)
            continue
        if name not in {"lowshelf", "highshelf", "equalizer"}:
            raise AudioDecodeError(f"Unsupported EQ preview filter: {name}")
        options = dict(field.split("=") for field in spec.split(":"))
        frequency, gain = float(options.pop("f")), float(options.pop("g"))
        if options != ({"t": "o", "w": "2"} if name == "equalizer" else {}):
            raise AudioDecodeError("Unsupported EQ preview bandwidth.")
        if 0 < frequency < rate / 2:
            sections.append(_biquad(name, frequency, gain, rate))

    filtered = np.empty_like(pcm)
    sos = np.asarray(sections)
    state = np.zeros((len(sections), 2, pcm.shape[1]))
    for start in range(0, len(pcm), _BLOCK_FRAMES):
        if cancel.is_set():
            raise CancelledError()
        stop = start + _BLOCK_FRAMES
        block = pcm[start:stop]
        if len(sos):
            block, state = sosfilt(sos, block, axis=0, zi=state)
        filtered[start:stop] = block * volume
    return filtered


def _limit_peaks(pcm: np.ndarray, rate: int, cancel: Event) -> None:
    if np.max(np.abs(pcm)) <= PEAK_LIMIT:
        return
    # Calculate one linked gain for both channels to preserve stereo balance.
    boundaries = np.arange(0, len(pcm), max(1, rate // 1000))
    peaks = np.maximum.reduceat(np.max(np.abs(pcm), axis=1), boundaries)
    gain = PEAK_LIMIT / np.maximum(peaks, PEAK_LIMIT)
    for index in range(1, len(gain)):
        gain[index] = min(gain[index], gain[index - 1] + (1 - gain[index - 1]) / 50)
    for index in range(len(gain) - 2, -1, -1):
        gain[index] = min(gain[index], gain[index + 1] + (1 - gain[index + 1]) / 5)
    # The gain at either edge cannot exceed the safe gain for that block.
    edges = np.r_[gain[0], np.minimum(gain[:-1], gain[1:]), gain[-1]]
    times = np.r_[boundaries, len(pcm)]
    for start in range(0, len(pcm), _BLOCK_FRAMES):
        if cancel.is_set():
            raise CancelledError()
        stop = min(start + _BLOCK_FRAMES, len(pcm))
        pcm[start:stop] *= np.interp(np.arange(start, stop), times, edges)[:, None]


class EqPreviewAudio:
    """One unfiltered PCM window per track dialog, reused across EQ changes."""

    def __init__(self) -> None:
        self._cached = None

    def render(
        self, source: Path, output: Path, audio_filter: str,
        start: float, duration: float | None, cancel: Event,
    ) -> None:
        try:
            import soundfile

            stat = source.stat()
            identity = (source, stat.st_size, stat.st_mtime_ns)
            cached = self._cached
            if cached is not None and cached[0] == identity:
                _, rate, total, channels, first, pcm = cached
            else:
                rate, total, channels = pcm_info(source)
                first, pcm = 0, None
            if channels not in (1, 2):
                raise AudioDecodeError("This audio window requires the FFmpeg preview path.")
            capacity = _PCM_CACHE_BYTES // (channels * 4)
            begin = round(start * rate)
            end = begin + capacity if duration is None else round((start + duration) * rate)
            if total is not None:
                begin = min(total, begin)
                end = total if duration is None else min(total, end)
            if end <= begin:
                raise AudioDecodeError("No audio remains at the requested position.")
            if end - begin > capacity:
                raise AudioDecodeError("This audio window requires the FFmpeg preview path.")
            if pcm is None or first > begin or first + len(pcm) < end:
                # Small playback movements during slider adjustments can reuse this window.
                first = begin
                cache_end = min(end + 5 * rate, first + capacity)
                if total is not None:
                    cache_end = min(total, cache_end)
                elif duration is None:
                    cache_end += 1  # Read one extra frame to detect an over-limit full track.
                pcm = read_pcm(
                    source, cancel, sample_rate=rate, channels=channels, start=first / rate,
                    duration=(cache_end - first) / rate,
                )
                if cancel.is_set():
                    raise CancelledError()
                if len(pcm) > capacity:
                    raise AudioDecodeError("This audio window requires the FFmpeg preview path.")
                if len(pcm) < cache_end - first:
                    total = first + len(pcm)
                    end = min(end, total)
                    if end <= begin:
                        raise AudioDecodeError("No audio remains at the requested position.")
                self._cached = (identity, rate, total, channels, first, pcm)
            filtered = _apply_eq(pcm[begin - first:end - first], rate, audio_filter, cancel)
            _limit_peaks(filtered, rate, cancel)
            # Retain the existing limiter's lookahead delay in the preview file.
            delay = min(len(filtered), max(0, rate // 200 - 1))
            if delay:
                filtered[delay:] = filtered[:-delay]
                filtered[:delay] = 0
            if cancel.is_set():
                raise CancelledError()
            soundfile.write(output, filtered, rate, subtype="PCM_24", compression_level=0)
        except AudioDecodeError:
            raise
        except (ImportError, KeyError, OSError, OverflowError, RuntimeError, TypeError, ValueError) as error:
            raise AudioDecodeError(str(error)) from error
